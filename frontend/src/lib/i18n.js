/** The text for the current language. `tr('{n} din', { n: 3 })` fills placeholders. */
export function tr(key, vars) {
  const row = STRINGS[key]
  let text = row ? row[lang === 'en' ? 0 : 1] : key
  if (vars) Object.entries(vars).forEach(([k, v]) => { text = text.split(`{${k}}`).join(v) })
  // "1 days left" reads wrong; Hindi needs no such change
  if (lang === 'en') {
    text = text.replace('Late 1 times', 'Late once').replace(/\b1 (days|times|customers|bills|batches|people|reminders)\b/, (_, w) => `1 ${w === 'batches' ? 'batch' : w === 'people' ? 'person' : w.slice(0, -1)}`)
  }
  return text
}

