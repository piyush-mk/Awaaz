// English / Hindi for the merchant app. Keys are the source strings used in the code.
// The choice lives on the device; changing it reloads the app, so every screen picks it up.
const KEY = 'awaaz.lang'

function read() {
  try {
    return window.localStorage.getItem(KEY) === 'en' ? 'en' : 'hi'
  } catch {
    return 'hi'
  }
}

export const lang = read()
if (typeof document !== 'undefined') document.documentElement.lang = lang

export function setLang(next) {
  if (next === lang) return
  try {
    window.localStorage.setItem(KEY, next)
  } catch {
    // private window: stays on this language
  }
  window.location.reload()
}

